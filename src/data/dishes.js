export const dishes = reactive([...localDishes])

// Mantiene la lista visible sincronizada con las recetas importadas que viven en el estado.
watch(
  () => state.imported,
  (imported) => {
    const wanted = new Set(imported.map((recipe) => recipe.id))
    for (let index = dishes.length - 1; index >= 0; index -= 1) {
      if (dishes[index].external && !wanted.has(dishes[index].id)) dishes.splice(index, 1)
    }
    for (const recipe of imported) {
      if (!dishes.some((dish) => dish.id === recipe.id)) dishes.push(recipe)
    }
  },
  { immediate: true, deep: true },
)

export function dishById(id) {
  return dishes.find((dish) => dish.id === id) ?? null
}
